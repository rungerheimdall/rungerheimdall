using System;
using Microsoft.CodeAnalysis;

namespace RungerHeimdall.Engine.Sources;

public static class SourceGuard
{
    public static bool IsGenerated(SyntaxTree tree)
    {
        if (tree is null)
        {
            return false;
        }

        var path = tree.FilePath;
        if (!string.IsNullOrEmpty(path))
        {
            var normalized = path!.Replace('\\', '/');

            if (normalized.IndexOf("/obj/", StringComparison.OrdinalIgnoreCase) >= 0)
            {
                return true;
            }

            if (normalized.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
                || normalized.EndsWith(".g.i.cs", StringComparison.OrdinalIgnoreCase)
                || normalized.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase)
                || normalized.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }
        }

        var root = tree.GetRoot();
        var firstToken = root.GetFirstToken(includeZeroWidth: true);
        if (firstToken.LeadingTrivia.Count == 0)
        {
            return false;
        }

        foreach (var trivia in firstToken.LeadingTrivia)
        {
            var text = trivia.ToString();
            if (text.IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) >= 0)
            {
                return true;
            }
        }

        return false;
    }
}